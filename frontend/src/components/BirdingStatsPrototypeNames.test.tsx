/** Drive the tab to its ready state. The section's own rAF gate is why this
 *  waits on rendered content rather than on a tick. */
async function renderStats() {
  render(<BirdingStats onGoToSettings={() => {}} onGoToWeather={() => {}} onOpenSpecies={() => {}} />)
  await waitFor(() => expect(screen.getByText('Statistics')).toBeTruthy(), { timeout: 10_000 })
  await waitFor(() => expect(screen.getByRole('heading', { name: 'Weather' })).toBeTruthy(), { timeout: 10_000 })
}

describe('a species named after a prototype member (security finding 1)', () => {
  it('does not crash the Statistics tab, and the Weather section renders', async () => {
    // The headline outcome: on the unfixed code `sciFor('__proto__')` returns
    // `Object.prototype`, React throws on it as a child, and the tab is gone.
    //
    // But this test CANNOT reject that revert, and saying so is the point.
    // `renderStats()` leaves the picker CLOSED, and the throw needs the options
    // rendered, so against the exact pre-fix shape this case stays green. The
    // test that actually holds the line is 'the picker lists every hostile name
    // with NO scientific name at all' below, which opens it; the source pin
    // holds the two protections apart, since either alone also stays green here
    // (they are redundant by design). Per .claude/rules/security.md, a
    // success-path fixture names the test that can reject the revert.
    const onError = vi.spyOn(console, 'error').mockImplementation(() => {})
    await renderStats()
    expect(screen.getByRole('heading', { name: 'Weather' })).toBeTruthy()
    // React logs its "Objects are not valid as a React child" through
    // console.error even where a boundary catches the throw, so a clean render
    // is asserted on the log too rather than only on the DOM.
    const shouted = onError.mock.calls.map(c => String(c[0])).join(' | ')
    expect(shouted).not.toMatch(/not valid as a React child/i)
    onError.mockRestore()
  })

  it('the picker lists every hostile name with NO scientific name at all', async () => {
    // Opening the picker is the whole trigger: `speciesOptions` maps `sciFor`
    // over every name, so the value is computed for all of them whether or not
    // one is chosen.
    await renderStats()
    const combo = screen.getByRole('combobox', { name: 'Filter by species' })
    fireEvent.focus(combo)
    const options = await screen.findAllByRole('option')
    const labels = options.map(o => o.textContent ?? '')

    for (const name of HOSTILE) {
      expect(labels.some(l => l.includes(name)), `${name} is offered`).toBe(true)
    }
    // The real name still resolves, so the table is doing its job rather than
    // being switched off -- the assertions above would pass on a `sciFor` that
    // always returned undefined.
    const crow = options.find(o => (o.textContent ?? '').includes('American Crow'))!
    expect(crow.textContent).toContain('Corvus brachyrhynchos')

    // And no option shows an inherited value. `[object Object]` is the
    // `__proto__` outcome; `function` the eleven-name outcome.
    for (const l of labels) {
      expect(l).not.toContain('[object Object]')
      expect(l.toLowerCase()).not.toContain('function')
    }
  })

  it('keeps BOTH protections, which only a source-level check can distinguish', () => {
    // See the header: each protection alone makes every behavioural assertion
    // above pass, so this is what stops one of them being dropped as redundant.
    // Resolved from the working directory, not from `import.meta.url`: this
    // file runs under jsdom, where `import.meta.url` is an http URL and
    // `fileURLToPath` throws. Vitest's cwd is `frontend/`.
    const src = stripComments(readFileSync(
      resolve(process.cwd(), 'src/components/BirdingStats.tsx'), 'utf8'))
    // Sliced to the memo and its accessor, so a match cannot come from an
    // unrelated table elsewhere in a 2,400-line file.
    const from = src.indexOf('const sciByNorm')
    const to = src.indexOf('const normTaxonOrder')
    expect(from, 'the sciByNorm memo is findable').toBeGreaterThan(-1)
    expect(to, 'the slice has an end').toBeGreaterThan(from)
    const body = src.slice(from, to)
    expect(body).toContain('Object.create(null)')
    expect(body).toContain('Object.hasOwn(m, norm)')
    expect(body).toContain('Object.hasOwn(sciByNorm, key)')
    // Non-vacuity: the stripper must not have eaten the code with the prose, or
    // three `toContain`s pass against an empty string.
    expect(body).toContain('const sciByNorm')
    expect(body.length).toBeGreaterThan(200)
    // And the shape that shipped to review must be gone, not merely joined.
    expect(body).not.toContain('sciByNorm[normalizeSpeciesName(name)]')
  })

  it('leaves Object.prototype untouched, which is the claim rather than the outcome', async () => {
    // Not exploitable for pollution -- the guarded write never runs for an
    // inherited key and the value is a string either way. Asserted so the claim
    // fails loudly if a later change makes it false.
    await renderStats()
    const probe = JSON.parse('{"__proto__":{"polluted":"yes"}}') as Record<string, unknown>
    expect(probe).toBeTruthy()
    expect(({} as Record<string, unknown>).polluted).toBeUndefined()
    expect(Object.prototype).not.toHaveProperty('polluted')
  })
})

/** Drop line and block comments. A source guard asserting a token is PRESENT
 *  must not be satisfied by a commented-out line -- the state a half-reverted
 *  change is in -- and one asserting a token is ABSENT must not be defeated by
 *  this file's own description of it. */
function stripComments(src: string): string {
  const OPEN = '/' + '*'
  const CLOSE = '*' + '/'
  const out: string[] = []
  let inBlock = false
  for (const line of src.split('\n')) {
    let l = line
    if (inBlock) {
      const c = l.indexOf(CLOSE)
      if (c === -1) continue
      inBlock = false
      l = l.slice(c + 2)
    }
    const o = l.indexOf(OPEN)
    if (o !== -1) {
      const c = l.indexOf(CLOSE, o + 2)
      if (c === -1) { inBlock = true; l = l.slice(0, o) }
      else l = l.slice(0, o) + l.slice(c + 2)
    }
    const lc = l.indexOf('//')
    if (lc !== -1) l = l.slice(0, lc)
    out.push(l)
  }
  return out.join('\n')
}
