// @vitest-environment jsdom
//
// A species name from the user's CSV must never reach a lookup table's
// PROTOTYPE (security review finding 1, Medium).
//
// `.claude/rules/security.md` writes this down twice -- `Object.hasOwn` on the
// read (v0.5.81) and `Object.create(null)` on the accumulator (v0.5.90) -- and
// the Statistics tab's `sciByNorm` / `sciFor` shipped to review with neither,
// because it was copied from the neighbouring table instead of from the rule.
//
// WHAT THAT COSTS, measured through the real aggregation rather than reasoned
// about. `Common Name` is a raw CSV column with no shape validation anywhere on
// its path, so on a bare `TABLE[key]`:
//
//   "__proto__"    -> Object.prototype, an OBJECT. React refuses to render it
//                     as a child, so the whole Statistics tab throws.
//   "constructor"  -> a truthy FUNCTION, which passes the `sciFor(...) &&`
//                     truthiness gate and then paints nothing: a silently wrong
//                     scientific name rather than an absent one. Eleven names
//                     behave this way (`toString`, `valueOf`, `hasOwnProperty`,
//                     `isPrototypeOf`, `toLocaleString`,
//                     `propertyIsEnumerable` and the four `__define*` /
//                     `__lookup*` accessors).
//
// Opening the picker is enough to reach it: `speciesOptions` maps `sciFor` over
// EVERY name and `SpeciesCombobox` renders each option's `sciName`, so no
// selection is required.
//
// WHY THE HOSTILE NAMES ARE IN THE FIXTURE'S CSV COLUMN and not written into a
// table by hand: `{ __proto__: x }` in source is special-cased by the language
// to set the prototype and creates NO own property, so a literal tests a shape
// that cannot arrive from storage. The rule says to build the probe with
// `JSON.parse`; going one better, this drives the REAL observation rows through
// the REAL memo, which is the path the value actually takes.
//
// THIS IS ALSO A POLLUTION PROBE, and it is expected to find none: the write is
// guarded and the value is a string, so `Object.prototype` is never touched.
// Asserted anyway, because "not exploitable for pollution" is a claim that
// should fail loudly if a later change makes it false.
//
// WHAT THE BEHAVIOURAL HALF CANNOT SEE, established by mutation rather than
// assumed. The fix has two protections and they are REDUNDANT: with
// `Object.create(null)` the table has no prototype to fall through to, and with
// `Object.hasOwn` the read never falls through. Removing EITHER alone leaves
// every test below green -- measured -- and only removing both turns them red.
// That is the "two mechanisms overlap and only one is guarded" shape, and the
// honest answer here is that there is no behaviour only one of them protects.
// So the pair is pinned at SOURCE level instead, which is the only instrument
// that can tell them apart, with comments stripped so this file's own
// explanation of the defect cannot satisfy the scan. The rule asks for both
// deliberately: the null prototype makes the table safe, and the guard makes
// that safety visible at the point of use, where a later reader cannot
// "simplify" it away invisibly.

