// Guard for improve: statistics-compute-off-thread.
//
// The Statistics tab's derivation chain moved out of a cascade of ~15 `useMemo`s in
// `components/BirdingStats.tsx` and into one pure function, so it can run in a
// worker. THE WHOLE POINT IS THAT NOTHING CHANGES, and "nothing changes" over a
// page of forty-odd figures, six ranked tables and five charts is not something a
// human eye is going to confirm by looking at it twice.
//
// So the pre-change cascade is written out here, verbatim, in the order and with
// the arguments `BirdingStats.tsx` used at 1.0.19 — and asserted equal to the
// bundle, field by field, across BOTH count rules and ALL FOUR accumulation
// granularities. If someone later "tidies" an argument in `statsBundle.ts` (feeds
// `computeGeo` the raw observations instead of the filtered ones, drops the
// escapee set from the second accumulation pass, reorders a call so a downstream
// consumer sees a different array), this is what says so.
//
// The fixture is deliberately awkward: forms the count rule drops, an escapee, a
// checklist whose only row is a spuh, several years and months, two same-named
// counties in different states, durations in and out of range, comment blocks, a
// breeding code, and an X count. A fixture that exercised only the easy path would
// let a swapped argument through.
