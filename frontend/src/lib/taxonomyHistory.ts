// Taxonomic splits, lumps and renames (taxonomic-splits-lumps, extended by
// recorded-names-in-splits-and-lumps): the asset's types and the derivation over
// the loaded backup. Pure: no React, no I/O, no Date.now(), no transport, no
// storage (schema.md section 6).
//
// RENAMES (recorded-names-in-splits-and-lumps, schema.md 6). The record keeps
// word-changing common-name renames in their own `renames` array, never in
// `events`, because the Statistics escapee join reads `events`. This module
// merges the two into one dated list at index build, and every structure below
// is built over that merged list. A rename's EARLIER name is reached by
// retired-name identity (tier 0) and by nothing else: never by code (its code is
// on its own event's after side) and never by the name tiers (it is not
// indexed there), so a name eBird has since given to another species can never
// count on the rename (FR-09). The cutoff that decides what is a rename lives in
// the generator alone (`renameKey`); nothing here re-derives it.
//
// The asset (`assets/ebird-taxonomy-history.json`) is a bundled BUILD-TIME
// artifact, generated by `scripts/build-taxonomy-history.mjs` and held to the
// bundled taxonomy snapshot by `taxonomyHistoryAsset.test.ts`. It is defended at
// build and CI time, never validated per entry at runtime (CLAUDE.md: a
// Vite-inlined JSON import is a different trust boundary from a persisted cache).
// The types below are the contract; the JSON is their literal form.
//
// ONE RULE, ONE RENDERER (NFR-07): countability is decided only by the shared
// `isNonCountableForm`, parent folding only by the shared `normalizeSpeciesName`,
// and code resolution only by the page's existing `/taxonomy/codes` result plus
// the asset-name fallback below. Nothing here classifies a name on its own.
//
// DECLARED SCAN OVER USER FILE CONTENT (schema.md 6.6 and, for this feature,
// recorded-names-in-splits-and-lumps schema.md section 8; security.md v1.0.23):
// `buildTaxonomyHistoryIndex` visits every row once. Per row it does one
// `isNonCountableForm`, one `normalizeSpeciesName` (memoized), one `Map.get` on
// the raw or merged name, per matched entry one lexical compare against a
// 10-character constant, and one `Map.get` on the RAW name in `keptByRawName`
// (the kept-form lookup). On a kept-form hit only, it loops over that name's
// before slots (one, by asset invariant K3) and over the key's matched entries
// (bounded by the asset), comparing integers, plus the same date compare. No
// nested scan, no regex over the name, no `includes` / `indexOf` / `find` /
// `filter` in the loop, so the pass is O(sum of row string lengths). Nothing is
// allocated per row or per distinct raw name: the kept-form counter is one
// integer per slot, sized by the asset. Key resolution runs once per DISTINCT
// merged key (cached in `entriesByKey`), each a handful of hash lookups plus,
// for a retired name only, `midChainTier0` (with the rename forward rule: one
// `Map.get` per matched earlier name of a rename) and, for a name-tier match,
// the rename closure (one `Map.get` per matched after entry). Then, once per
// AFFECTED key, `lineageEvents` walks each matched entry's line, visiting each
// event at most once per direction. Both per-key walks are bounded by the asset,
// never by the file, so the total is O(distinct keys x the asset's chain bound):
// linear in the rows (schema.md 6.6, corrected at the security review). No loop
// is driven by a number read from the file: dates are compared lexically and
// never iterated. Measured linear through this entry point, including a hostile
// leg of 4,000-character names and dates, a leg where every row is a distinct
// affected key over the real asset, and legs where every row carries a kept
// form or a rename's retired earlier name, in `taxonomyHistory.test.ts`.
//
// MEMORY: the index retains per entry three integers and one key reference, per
// distinct key one small array of entry ids, and nothing per row. It is an
// in-memory derived value keyed on a user data file, so it is OUTSIDE
// `clearDerived.ts` by design (that registry holds on-disk documents only): what
// terminates it is the page's memo, whose `observations` dependency changes on
// every new load, leaving the old index unreachable.

