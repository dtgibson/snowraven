// ── The asset contract (schema.md 3.2) ─────────────────────────────────────────

/** The three kinds of change the record holds. */
export type HistoryKind = 'split' | 'lump' | 'rename'

export interface TaxonomyHistory {
  /** Asset schema version. 2 since renames joined; any other value is a load
   *  failure (FR-28), so a record without `renames` is never read as "no
   *  renames". */
  v: 2
  /** `version` of the bundled taxonomy snapshot every current-side code was
   *  resolved against. CI asserts equality with the snapshot. */
  snapshot: string
  /** ISO date the generator ran. Provenance only. */
  generated: string
  /** The input files the generator read, by basename. Provenance only. */
  inputs: string[]
  /** Every update the asset covers, ascending. An update with zero events is
   *  never listed, so coverage never claims a year the generator could not read. */
  updates: HistoryUpdate[]
  /** First and last of `updates`, or null when `updates` is empty. */
  coverage: { earliest: HistoryUpdate; latest: HistoryUpdate } | null
  /** Splits and lumps ONLY, ascending by `published`, then by the before side's
   *  first scientific name. No rename is ever a member: the escapee join reads
   *  this array (exoticTaxonomyJoin.ts). */
  events: HistoryEvent[]
  /** Word-changing common-name renames (recorded-names-in-splits-and-lumps),
   *  ascending by `published`, then by the earlier name's scientific name. */
  renames: HistoryRename[]
}

/** One rename: the code is the same on both sides; the earlier name is the
 *  previous update's file's, the current one this update's file's, never
 *  rewritten to the snapshot's (so a code renamed twice reads A to B, then B to
 *  C). Dated to the update whose file first carries the new name, and nothing
 *  finer (FR-04). */
export interface HistoryRename {
  kind: 'rename'
  year: number
  published: string
  before: [HistoryBeforeEntry]
  after: [HistoryEntry]
  slashes: []
}

export interface HistoryUpdate {
  /** eBird/Clements update year, e.g. 2025. */
  year: number
  /** The day eBird announced the update complete, YYYY-MM-DD. */
  published: string
}

export interface HistoryEvent {
  kind: 'split' | 'lump'
  year: number
  published: string
  /** A split has exactly one; a lump has two or more. */
  before: HistoryBeforeEntry[]
  /** A split has two or more; a lump has exactly one. */
  after: HistoryEntry[]
  /** Slash taxa the split created. Empty for a lump. */
  slashes: HistoryEntry[]
}

export interface HistoryEntry {
  code: string
  sci: string
  com: string
}

export interface HistoryBeforeEntry extends HistoryEntry {
  /** true when `com` is NOT a species common name in the bundled snapshot: the
   *  tier-0 gate below (only a retired common name is evidence of an export made
   *  before the update). */
  retired: boolean
  /** Lump earlier names only: the present name of the form eBird kept for this
   *  name (its own code, now reporting as the lumped species). Present exactly
   *  when such a form exists (FR-06, asset invariant K1); absent otherwise. */
  form?: string
}

// ── The derivation's inputs and output (schema.md 6.1, 6.4) ──────────────────

export interface HistoryCodeLookup {
  /** The page's existing `/taxonomy/codes` result, keyed by the name AS SENT.
   *  Read only through Object.hasOwn: a species name out of the CSV is an
   *  external-string key (security.md v0.5.81). Empty when the batch failed or has
   *  not landed; only the name tiers then apply. */
  codes: Readonly<Record<string, string>>
}

export interface AffectedEvent {
  eventIndex: number
  kind: HistoryKind
  year: number
  /** True when the user's rows under this key matched the event itself; false
   *  when the event is reached only through the chain (FR-03, FR-15). */
  direct: boolean
}

export interface AffectedSpecies {
  key: string
  /** Every event that touches the key, directly or through the chain, in date
   *  order ascending. The list shows these most recent first; the section shows
   *  them earliest first. */
  events: readonly AffectedEvent[]
}

export interface EntryView {
  code: string
  sci: string
  com: string
  /** Rows matched to this entry in the FULL backup. 0 = no reports under it. */
  count: number
  /** Rows dated on or before the update's published day. */
  onOrBefore: number
  /** Rows dated after it. Always `count - onOrBefore`. */
  after: number
  /** The merged key whose rows matched this entry (first seen wins), or null when
   *  `count` is 0 or the entry is a slash. */
  speciesKey: string | null
  /** True only for an after-side entry whose code is still a species after every
   *  covered update: the one kind of entry that may carry the eBird and Birds of
   *  the World marks (FR-23). False for an after code a later update retired
   *  (Macquarie Parakeet's `recpar23`), and always false on the before side and
   *  for a slash. On a rename's current name it is also false unless this is
   *  the LATEST rename of the code, so site marks never sit beside a name the
   *  code no longer carries. See `currentAfterCode` in
   *  `buildTaxonomyHistoryIndex`. */
  current: boolean
  /** '' unless this is a traced earlier name of a lump: then the kept form's
   *  present name (FR-06, FR-22). */
  form: string
  /** The earlier-name figure or state (FR-13 to FR-21). Meaningful on before
   *  entries only; `{ state: 'none' }` on every after and slash entry and on
   *  every before entry of an event whose `earlierState` is not 'counted'. */
  earlier: EarlierFigure
}

/** An earlier name's figure. `n === 0` is the zero state (FR-19); 'untraceable'
 *  carries which of FR-18's two sentences is true. Absence is `{ state:
 *  'none' }`, never a null member. */
export type EarlierFigure =
  | { readonly state: 'none' }
  | { readonly state: 'count'; readonly n: number }
  | { readonly state: 'untraceable'; readonly reason: 'survivor' | 'no-form' }

export interface EventView {
  kind: HistoryKind
  year: number
  published: string
  before: readonly EntryView[]
  after: readonly EntryView[]
  /** Only the slashes the user holds rows under (count > 0). */
  slashes: readonly EntryView[]
  /** FR-19: some before entry has count > 0 and every after entry has count 0. */
  predates: boolean
  /** Decided once per event, in FR-20, then FR-21, then FR-13 to FR-19 order:
   *  'pre-update' when the backup still carries an earlier name (the shipped
   *  figures only), 'later-changed' when a later split or lump changed one of
   *  this event's current-side codes (a marker, no figure), else 'counted'. */
  earlierState: 'pre-update' | 'later-changed' | 'counted'
  /** Lump only, while 'counted' with at least one traced earlier name: the
   *  "Earlier name not recorded" count (FR-17). 0 otherwise; the box shows
   *  only when it is above 0. */
  residual: number
}

export interface TaxonomyHistoryIndex {
  coverage: TaxonomyHistory['coverage']
  /** Merged keys that matched at least one entry, in first-seen order. */
  affected: ReadonlyMap<string, AffectedSpecies>
  /** Every event of the merged list (splits, lumps and renames by date), with
   *  per-entry tallies attached, index-addressable. */
  events: readonly EventView[]
}

/** One row of the list control (FR-11, FR-30): events most recent first. */
export interface HistoryListEntry {
  species: string
  events: readonly { kind: HistoryKind; year: number }[]
}

// ── Implementation ─────────────────────────────────────────────────────────────

type Side = 'before' | 'after' | 'slash'

/** A member of the merged, dated list: a split, a lump or a rename. */
type AnyEvent = HistoryEvent | HistoryRename

interface EntrySlot {
  event: number
  side: Side
  entry: HistoryEntry
  count: number
  onOrBefore: number
  speciesKey: string | null
  /** Lump before slots with a kept form only: this slot's rows dated on or
   *  before the update that carry the form and were tallied on the lump's
   *  after entry (FR-16). One integer per slot, sized by the asset. */
  formOnOrBefore: number
}

const lower = (s: string) => s.toLowerCase()

/** The (sci, com) key of the pair tier, lowercased, joined on U+0000. */
const pairKey = (sci: string, com: string): string => `${lower(sci)}\u0000${lower(com)}`

/** One set of name-tier maps (schema.md 6.2 tier 2). */
interface NameTier {
  byPair: Map<string, number[]>  // (sci, com)
  bySci: Map<string, number[]>   // sci alone
  byCom: Map<string, number[]>   // com alone
}

const NO_FIGURE: EarlierFigure = Object.freeze({ state: 'none' })

/**
 * Splits and lumps, then renames, in one list by published date, with splits
 * and lumps first on an equal date (schema.md 6.1). One linear merge of two
 * already-sorted arrays; the members are the record's own objects, never copies.
 */
function mergedEvents(history: TaxonomyHistory): AnyEvent[] {
  const sl = history.events
  const rn = history.renames
  const out: AnyEvent[] = []
  let i = 0
  let j = 0
  while (i < sl.length || j < rn.length) {
    if (j >= rn.length || (i < sl.length && sl[i].published <= rn[j].published)) out.push(sl[i++])
    else out.push(rn[j++])
  }
  return out
}

function pushTo<K>(map: Map<K, number[]>, key: K, id: number): void {
  const list = map.get(key)
  if (list) list.push(id)
  else map.set(key, [id])
}

/** The first name tier that answers in one set of maps: pair, then sci, then
 *  com, with the after side preferred per event. Empty when none answers. */
function nameTierMatch(t: NameTier, key: string, sci: string, slots: readonly EntrySlot[]): number[] {
  const pair = t.byPair.get(pairKey(sci, key))
  if (pair) return preferAfterPerEvent(pair, slots)
  const s = t.bySci.get(lower(sci))
  if (s) return preferAfterPerEvent(s, slots)
  const c = t.byCom.get(lower(key))
  if (c) return preferAfterPerEvent(c, slots)
  return []
}

/** Per event, keep the after-side candidates when any exist, else the before-side
 *  ones: the sci-name step's precedence (schema.md 6.2 tier 2), applied per event
 *  so a chained lineage keeps its match on both of its events. */
function preferAfterPerEvent(ids: readonly number[], slots: readonly EntrySlot[]): number[] {
  const byEvent = new Map<number, number[]>()
  for (const id of ids) pushTo(byEvent, slots[id].event, id)
  const out: number[] = []
  for (const list of byEvent.values()) {
    const after = list.filter(id => slots[id].side === 'after')
    out.push(...(after.length > 0 ? after : list))
  }
  return out
}

/**
 * The index over the full backup (schema.md section 6). Filters and toggles are
 * structurally not inputs (FR-09, FR-24), so the page memoizes this on the
 * observations array, the loaded asset and the codes result only.
 */
export function buildTaxonomyHistoryIndex(
  observations: readonly ObservationEntry[],
  history: TaxonomyHistory,
  lookup: HistoryCodeLookup,
): TaxonomyHistoryIndex {
  // ── The merged, dated list (schema.md 6.1): every structure below is built
  // over it, and `eventIndex` addresses it.
  const all = mergedEvents(history)

  // ── Entry slots and the asset-side indexes (O(events x entries), once) ──
  const slots: EntrySlot[] = []
  const eventSlots: { before: number[]; after: number[]; slashes: number[] }[] = []
  const retiredByCom = new Map<string, number[]>()   // tier 0
  const afterByCode = new Map<string, number[]>()    // tier 1
  const beforeByCode = new Map<string, number[]>()   // tier 1 (only where no after has it)
  // Tier 2, the name tiers: split and lump entries in one set of maps, exactly
  // as shipped, and renames' CURRENT names in their own (see `resolve`).
  const slNames: NameTier = { byPair: new Map(), bySci: new Map(), byCom: new Map() }
  const rnNames: NameTier = { byPair: new Map(), bySci: new Map(), byCom: new Map() }
  const slashByRawName = new Map<string, number[]>() // FR-08's exact-name exception
  const renameAfterByCode = new Map<string, number[]>() // the tier-2 rename closure
  const slBeforeByCode = new Map<string, number[]>()    // the tier-0 rename forward rule
  // Kept form name, exactly as the snapshot spells it, to the lump before slots
  // that carry it (one, by asset invariant K3). A Map, so a backup name such as
  // `__proto__` is an ordinary miss (security.md, external-string keys).
  const keptByRawName = new Map<string, number[]>()

  // When each code was last created on an after side. A before code that a
  // LATER event creates again was re-used by eBird (a lumped species split back
  // out under its old code: Pilbara Grasswren, lumped 2021 and split 2024; a
  // split parent's code given to a later lump of its daughters: Chestnut-naped
  // Spurfowl, 2022). A current export's code is that later species, so such a
  // before entry is not indexed by code: a 2025 "Pilbara Grasswren" row lands
  // on the 2024 split's after side and the 2021 lump stays on its line through
  // the chain, never as a before-side row that would read "Your backup
  // predates the 2021 update". Asset invariant I6 admits exactly these codes.
  const lastAfterAt = new Map<string, string>()
  for (const ev of all) {
    for (const a of ev.after) {
      const at = lastAfterAt.get(a.code)
      if (at === undefined || ev.published > at) lastAfterAt.set(a.code, ev.published)
    }
  }

  all.forEach((ev, e) => {
    const mk = (entry: HistoryEntry, side: Side): number => {
      slots.push({ event: e, side, entry, count: 0, onOrBefore: 0, speciesKey: null, formOnOrBefore: 0 })
      return slots.length - 1
    }
    const before = ev.before.map(b => mk(b, 'before'))
    const after = ev.after.map(a => mk(a, 'after'))
    const slashes = ev.slashes.map(s => mk(s, 'slash'))
    eventSlots.push({ before, after, slashes })

    // A rename's earlier name joins `retiredByCom` here like any before entry,
    // and `beforeByCode` never takes it: its code is on its own after side.
    const afterCodes = new Set(ev.after.map(a => a.code))
    before.forEach((id, i) => {
      const b = ev.before[i]
      if (b.retired) pushTo(retiredByCom, lower(b.com), id)
      const reusedLater = (lastAfterAt.get(b.code) ?? '') > ev.published
      if (!afterCodes.has(b.code) && !reusedLater) pushTo(beforeByCode, b.code, id)
      if (ev.kind !== 'rename') pushTo(slBeforeByCode, b.code, id)
      if (ev.kind === 'lump' && typeof b.form === 'string') pushTo(keptByRawName, b.form, id)
    })
    for (const id of after) pushTo(afterByCode, slots[id].entry.code, id)
    if (ev.kind === 'rename') for (const id of after) pushTo(renameAfterByCode, slots[id].entry.code, id)
    // The name tiers index a rename's CURRENT name only: its earlier name is
    // reached by retired-name identity and nothing else (FR-09).
    const names = ev.kind === 'rename' ? rnNames : slNames
    for (const id of (ev.kind === 'rename' ? after : [...before, ...after])) {
      const { sci, com } = slots[id].entry
      pushTo(names.byPair, pairKey(sci, com), id)
      pushTo(names.bySci, lower(sci), id)
      pushTo(names.byCom, lower(com), id)
    }
    for (const id of slashes) pushTo(slashByRawName, slots[id].entry.com, id)
  })

  /**
   * Tier 0 on a chain (QA fix errand 2). A retired name is the name the export
   * was made under, so a row carrying it PREDATES the update that retired it and
   * matches that update's before-side entry. But the name was CURRENT after any
   * EARLIER covered update whose after side carries the same code: an export
   * made between the two updates carries it (Macquarie Parakeet, current after
   * the 2023 split and lumped in 2024). So the row also matches each such earlier
   * after-side entry, by code (the after entry carries today's name, which may
   * differ from the export's, e.g. South Papuan Pitta shown as Papuan Pitta),
   * and at that earlier event it is an after-side row, not a before-side one:
   * where the same event also matched on its before side (a name the split KEPT,
   * like Slender-billed Crow in 2023), the after entry wins, one entry per event.
   * Each event's partition and its FR-19 "predates" reading then follow from the
   * row's side at THAT event: a 1 March 2024 Slender-billed Crow row is
   * "recorded since" at the 2023 split and predates only the 2024 update.
   *
   * Stated limit, the same kind as schema.md 6.2's: at an update that KEPT the
   * name (Slender-billed Crow, 2023), a backup exported BEFORE that update
   * carries the same name, and such a row is read as an export made after it.
   *
   * THE RENAME FORWARD RULE (recorded-names-in-splits-and-lumps, schema.md
   * 6.2). A rename does not change which species a code means, so a row under
   * a rename's retired earlier name predates every LATER update on that code:
   * it also matches each split or lump BEFORE entry with the same code at an
   * event published after the rename. It is never extended to a later rename's
   * earlier name (FR-09: only a report under that name counts there). Without
   * it, Siao Pitta lost its "predates the 2023 lump" reading.
   */
  const midChainTier0 = (matched: readonly number[]): number[] => {
    const ids = new Set(matched)
    for (const id of matched) {
      const { event, entry } = slots[id]
      for (const a of afterByCode.get(entry.code) ?? []) {
        if (all[slots[a].event].published < all[event].published) ids.add(a)
      }
      if (all[event].kind !== 'rename') continue
      for (const b of slBeforeByCode.get(entry.code) ?? []) {
        if (all[slots[b].event].published > all[event].published) ids.add(b)
      }
    }
    const afterEvents = new Set([...ids].filter(id => slots[id].side === 'after').map(id => slots[id].event))
    return [...ids].filter(id => slots[id].side === 'after' || !afterEvents.has(slots[id].event))
  }

  /**
   * The tier-2 rename closure (schema.md 6.2). Tier 1 reaches every after entry
   * with the resolved code, renames included; a name-tier match reaches only
   * the entries whose names it matched. So for each matched after entry, add
   * every rename's current-name entry with the same code, or a code renamed
   * twice would show its first rename as a chain-only line with no tallies
   * whenever the codes batch has not landed. One `Map.get` per matched entry.
   */
  const closeRenames = (ids: number[]): number[] => {
    let out: Set<number> | null = null
    for (const id of ids) {
      if (slots[id].side !== 'after') continue
      const more = renameAfterByCode.get(slots[id].entry.code)
      if (more === undefined) continue
      if (out === null) out = new Set(ids)
      for (const m of more) out.add(m)
    }
    return out === null ? ids : [...out]
  }

  // ── Key resolution (schema.md 6.2), once per distinct merged key ──
  const resolve = (key: string, sci: string): number[] => {
    // Tier 0: a retired before-side common name is direct evidence of an export
    // made before the update that retired it (finding 2.2), so it wins before
    // any code runs.
    const t0 = retiredByCom.get(lower(key))
    if (t0) return midChainTier0(t0)

    // Tier 1: the current code the page already resolved.
    const code = Object.hasOwn(lookup.codes, key) ? lookup.codes[key] : undefined
    if (typeof code === 'string' && SPECIES_CODE_RE.test(code)) {
      return [...(afterByCode.get(code) ?? []), ...(beforeByCode.get(code) ?? [])]
    }

    // Tier 2: only when tier 1 yielded no code at all. Pair, then sci, then com;
    // the scientific name wins over a conflicting common name. Split and lump
    // entries first, exactly as shipped; a rename's current name only when they
    // find nothing. Sharing one set of maps let a rename's pair match pre-empt a
    // split's common-name match (measured: Comoro Cuckooshrike under its 2023
    // scientific name lost its after-side count at the 2019 split), a reading
    // FR-20 forbids to change. So the split and lump entries a row reaches here
    // are always the shipped ones, and the closure adds only renames.
    const sl = nameTierMatch(slNames, key, sci, slots)
    return closeRenames(sl.length > 0 ? sl : nameTierMatch(rnNames, key, sci, slots))
  }

  // The one date comparison (FR-11): lexical compare of YYYY-MM-DD strings, the
  // page's own date-filter convention; a row dated exactly on the published day
  // is on-or-before. The kept-form count below uses this same function.
  const onOrBeforeEvent = (date: string, e: number): boolean => date <= all[e].published

  const tally = (id: number, date: string, key: string | null): void => {
    const slot = slots[id]
    slot.count += 1
    if (onOrBeforeEvent(date, slot.event)) slot.onOrBefore += 1
    if (key !== null && slot.speciesKey === null) slot.speciesKey = key
  }

  // ── The row pass (schema.md 6.3, 6.4): every row visited once ──
  const entriesByKey = new Map<string, number[]>()
  for (const o of observations) {
    if (isNonCountableForm(o.commonName)) {
      const ids = slashByRawName.get(o.commonName)
      if (ids) for (const id of ids) tally(id, o.date, null)
      continue
    }
    const key = normalizeSpeciesName(o.commonName)
    let ids = entriesByKey.get(key)
    if (ids === undefined) {
      ids = resolve(key, o.scientificName)
      entriesByKey.set(key, ids)
    }
    for (const id of ids) tally(id, o.date, key)
    // FR-16: a row whose reported name, exactly as the backup spells it, is a
    // lump earlier name's kept form, dated on or before that lump, and tallied
    // on that lump's after entry, counts under the earlier name. Integer
    // compares only; hand-written loops, nothing that searches.
    const kept = keptByRawName.get(o.commonName)
    if (kept === undefined) continue
    for (let k = 0; k < kept.length; k += 1) {
      const b = kept[k]
      const e = slots[b].event
      if (!onOrBeforeEvent(o.date, e)) continue
      for (let j = 0; j < ids.length; j += 1) {
        const s = slots[ids[j]]
        if (s.event === e && s.side === 'after') { slots[b].formOnOrBefore += 1; break }
      }
    }
  }

  // ── The chain (FR-03, FR-15), over the asset alone ──
  // Which events carry each code on each side. A lineage is walked from the
  // matched entry in ONE direction at a time (lineageEvents below).
  const withBefore = new Map<string, number[]>()
  const withAfter = new Map<string, number[]>()
  all.forEach((ev, e) => {
    for (const b of ev.before) pushTo(withBefore, b.code, e)
    for (const a of ev.after) pushTo(withAfter, a.code, e)
  })
  const published = (e: number) => all[e].published

  /**
   * Whether an after-side code is still a species (security review L1). Asset
   * invariant I5 admits an after code that is no longer a species when a LATER
   * covered update carries it on its before side (the chain), and I6 requires a
   * before code that IS still a species to be kept on its own event's after
   * side or created again on a later one's (a re-used code, above). So a code
   * is current exactly when the latest update that carries it has it on an
   * after side. Retired: Macquarie Parakeet (`recpar23`), after in
   * 2023, before only in 2024. Kept: Red-crowned Parakeet (`refpar4`), after in
   * 2023, before AND after in 2024. The shorter test "never on a later before
   * side" would wrongly drop the kept code's links, so it is not used.
   * `taxonomyHistoryAsset.test.ts` holds this to the snapshot over the whole
   * committed asset. Asset only, O(events x entries), once per index build.
   */
  const lastSeen = new Map<string, { published: string; onAfter: boolean }>()
  for (const ev of all) {
    const mark = (code: string, onAfter: boolean): void => {
      const prev = lastSeen.get(code)
      if (prev === undefined || ev.published > prev.published) lastSeen.set(code, { published: ev.published, onAfter })
      else if (ev.published === prev.published && onAfter) prev.onAfter = true
    }
    for (const b of ev.before) mark(b.code, false)
    for (const a of ev.after) mark(a.code, true)
  }
  const currentAfterCode = (code: string): boolean => lastSeen.get(code)?.onAfter === true

  /**
   * The events on ONE entry's own line of descent (FR-11, FR-15: "every covered
   * event that touches" the species). Forward, the line runs through the entry
   * itself (an after entry) or through its event's after side (a before entry,
   * whose reports went there), then through each later event that takes one of
   * those codes on its before side, and on through that event's after side.
   * Backward, it runs through the entry itself (a before entry) or its event's
   * before side (an after entry came from those), then through each earlier
   * event that produced one of those codes. The walk NEVER turns around: a
   * daughter does not inherit a sibling's later change, and a lump's co-parent
   * does not inherit its partner's earlier split. schema.md 6.5 closed over
   * links in both directions at once, which is the whole connected component
   * and attached a sibling's later split to a species it never touched
   * (decisions.md, Stage 5 QA fix 1).
   */
  const lineageEvents = (id: number, out: Set<number>): void => {
    const slot = slots[id]
    const e = slot.event
    out.add(e)
    const ev = all[e]
    const forwardFrom = slot.side === 'before' ? ev.after.map(a => a.code) : [slot.entry.code]
    const backwardFrom = slot.side === 'before' ? [slot.entry.code] : ev.before.map(b => b.code)

    const fwdSeen = new Set<number>()
    const fwd: [string, string][] = forwardFrom.map(c => [c, ev.published])
    while (fwd.length > 0) {
      const [code, t] = fwd.pop()!
      for (const f of withBefore.get(code) ?? []) {
        if (published(f) <= t || fwdSeen.has(f)) continue
        fwdSeen.add(f)
        out.add(f)
        for (const a of all[f].after) fwd.push([a.code, published(f)])
      }
    }

    const bwdSeen = new Set<number>()
    const bwd: [string, string][] = backwardFrom.map(c => [c, ev.published])
    while (bwd.length > 0) {
      const [code, t] = bwd.pop()!
      for (const g of withAfter.get(code) ?? []) {
        if (published(g) >= t || bwdSeen.has(g)) continue
        bwdSeen.add(g)
        out.add(g)
        for (const b of all[g].before) bwd.push([b.code, published(g)])
      }
    }
  }

  // ── Later-changed events (FR-21, schema.md 6.6) ──
  // When a split or lump last listed each code on its before side. An event is
  // later-changed when a LATER split or lump takes one of its current-side
  // codes: its earlier-name figure would then miss reports moved to another
  // code, or count reports moved in. A later rename never makes an event
  // later-changed, because a rename moves no report.
  const lastSLBefore = new Map<string, string>()
  for (const ev of all) {
    if (ev.kind === 'rename') continue
    for (const b of ev.before) {
      const at = lastSLBefore.get(b.code)
      if (at === undefined || ev.published > at) lastSLBefore.set(b.code, ev.published)
    }
  }
  const laterChanged = (ev: AnyEvent): boolean => {
    for (const c of ev.after) if ((lastSLBefore.get(c.code) ?? '') > ev.published) return true
    for (const c of ev.slashes) if ((lastSLBefore.get(c.code) ?? '') > ev.published) return true
    return false
  }
  // The latest rename of each code: only its current name may carry the site
  // marks (FR-27). The merged list is in date order, so the last write wins.
  const lastRenameAt = new Map<string, string>()
  for (const ev of all) if (ev.kind === 'rename') lastRenameAt.set(ev.after[0].code, ev.published)

  const events: EventView[] = all.map((ev, e) => {
    const view = (id: number): EntryView => {
      const s = slots[id]
      const isCurrent = s.side === 'after' && currentAfterCode(s.entry.code)
        && (ev.kind !== 'rename' || lastRenameAt.get(s.entry.code) === ev.published)
      return {
        code: s.entry.code, sci: s.entry.sci, com: s.entry.com,
        count: s.count, onOrBefore: s.onOrBefore, after: s.count - s.onOrBefore,
        speciesKey: s.side === 'slash' || s.count === 0 ? null : s.speciesKey,
        current: isCurrent,
        form: '',
        earlier: NO_FIGURE,
      }
    }
    const after = eventSlots[e].after.map(view)
    const allSlashes = eventSlots[e].slashes.map(view)
    const slashes = allSlashes.filter(v => v.count > 0)
    const beforeSlots = eventSlots[e].before
    const preUpdate = beforeSlots.some(id => slots[id].count > 0)
    // FR-20 first, then FR-21, then FR-13 to FR-19.
    const earlierState: EventView['earlierState'] = preUpdate ? 'pre-update' : laterChanged(ev) ? 'later-changed' : 'counted'

    // The figure for a split or a rename: the reassigned figures of every
    // current-side name, every slash the split created included, drawn or not
    // (FR-13, FR-15). Equal to them by construction, never a second count.
    let reassigned = 0
    for (const a of after) reassigned += a.onOrBefore
    for (const x of allSlashes) reassigned += x.onOrBefore

    let traced = 0
    let anyTraced = false
    const before = beforeSlots.map((id, i): EntryView => {
      const v = view(id)
      const src = ev.before[i]
      if (ev.kind === 'lump' && typeof src.form === 'string') v.form = src.form
      if (earlierState !== 'counted') return v
      if (ev.kind !== 'lump') {
        v.earlier = { state: 'count', n: reassigned }
      } else if (v.form !== '') {
        v.earlier = { state: 'count', n: slots[id].formOnOrBefore }
        traced += slots[id].formOnOrBefore
        anyTraced = true
      } else {
        v.earlier = { state: 'untraceable', reason: src.code === ev.after[0].code ? 'survivor' : 'no-form' }
      }
      return v
    })
    // FR-17: the lumped name's reassigned figure less every traced count; never
    // negative, because a row adds to at most one traced counter per lump (K3)
    // and only when it was also tallied on-or-before on the lump's after entry.
    const residual = ev.kind === 'lump' && earlierState === 'counted' && anyTraced
      ? after[0].onOrBefore - traced
      : 0
    return {
      kind: ev.kind, year: ev.year, published: ev.published,
      before, after, slashes,
      predates: before.some(b => b.count > 0) && after.every(a => a.count === 0),
      earlierState,
      residual,
    }
  })

  // ── Affected keys: the direct events plus each matched entry's own line ──
  const affected = new Map<string, AffectedSpecies>()
  for (const [key, ids] of entriesByKey) {
    if (ids.length === 0) continue
    const direct = new Set(ids.map(id => slots[id].event))
    const seen = new Set<number>()
    for (const id of ids) lineageEvents(id, seen)
    const ordered = [...seen].sort((a, b) =>
      all[a].published < all[b].published ? -1
        : all[a].published > all[b].published ? 1 : a - b)
    affected.set(key, {
      key,
      events: ordered.map(e => ({
        eventIndex: e, kind: all[e].kind, year: all[e].year, direct: direct.has(e),
      })),
    })
  }

  return { coverage: history.coverage, affected, events }
}

/** The lineage for one merged key, or null when the key is not affected. */
export function lineageFor(index: TaxonomyHistoryIndex, key: string | null): AffectedSpecies | null {
  if (key === null) return null
  return index.affected.get(key) ?? null
}

/** The list control's entries (FR-11): affected keys in the selector's order,
 *  each with its events most recent first. */
export function historyListEntries(
  index: TaxonomyHistoryIndex,
  speciesOrder: readonly string[],
): HistoryListEntry[] {
  const out: HistoryListEntry[] = []
  for (const species of speciesOrder) {
    const a = index.affected.get(species)
    if (!a) continue
    out.push({ species, events: [...a.events].reverse().map(e => ({ kind: e.kind, year: e.year })) })
  }
  return out
}
