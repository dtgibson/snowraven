describe('the coverage denominator is the ATTRIBUTION gate (FR-13)', () => {
  it('counts SnowRaven and RainCrow blocks alike', () => {
    const { stats } = build([
      { comment: srBlock(60) },
      { comment: rcBlock('Temperature: 60°F  Wind: Calm') },
    ])
    expect(stats.foundCount).toBe(2)
    expect(stats.readableCount).toBe(2)
  })

  it('a comment with weather LABELS and no app credit counts in NEITHER the found nor the unreadable count', () => {
    const { stats } = build([
      { comment: unattributed('Temperature: 60°F  Wind: Calm  Humidity: 50%') },
      { comment: 'A lovely morning.' },
      { comment: '' },
    ])
    expect(stats.foundCount).toBe(0)
    expect(stats.readableCount).toBe(0)
    expect(stats.unreadableCount).toBe(0)
    expect(stats.totalChecklists).toBe(3)
  })

  it('found === readable + unreadable, always', () => {
    const { stats } = build([
      { comment: srBlock(60) },
      { comment: rcBlock('Temperature: nope  Wind: nope', '🦅') },
      { comment: unattributed('Temperature: 60°F  Wind: Calm') },
      { comment: 'prose' },
    ])
    expect(stats.foundCount).toBe(2)
    expect(stats.readableCount).toBe(1)
    expect(stats.unreadableCount).toBe(1)
    expect(stats.foundCount).toBe(stats.readableCount + stats.unreadableCount)
  })

  it('the found count is NOT required to equal the complement of the looser label-based test', () => {
    // The Weather tab's backlog uses the looser `hasWeatherBlock`, which matches
    // an uncredited block. The two figures differ DELIBERATELY, and this is the
    // assertion that keeps a future "consistency fix" from quietly coupling
    // them. `docs/HELP.md` states the difference.
    const { stats } = build([
      { comment: unattributed('Temperature: 60°F  Wind: Calm  Humidity: 50%') },
      { comment: srBlock(60) },
    ])
    expect(stats.totalChecklists).toBe(2)
    expect(stats.foundCount).toBe(1)
    expect(stats.totalChecklists - stats.foundCount).toBe(1)
  })
})

// ── Denominators and sums (FR-21, FR-22, FR-23) ─────────────────────────────

describe('every distribution sums to its OWN denominator (FR-21)', () => {
  it('the three axes sum independently, and legitimately differ', () => {
    const { stats } = build([
      // A condition and a temperature and a wind.
      { comment: srBlock(60) },
      // A temperature and a wind, no condition (an unrecognized header glyph).
      { comment: rcBlock('Temperature: 60°F  Wind: Calm', '🦅') },
      // A condition and a temperature, no wind (an unrecognized Beaufort word).
      { comment: rcBlock('Temperature: 60°F  Wind: quite blowy') },
      // A condition only.
      { comment: rcBlock('Humidity: 50%') },
    ])
    expect(stats.readableCount).toBe(4)
    const sum = (rows: Array<{ checklists: number }>) => rows.reduce((n, r) => n + r.checklists, 0)
    expect(sum(stats.byCondition)).toBe(3)
    expect(sum(stats.byTempBand)).toBe(3)
    expect(sum(stats.byWindBand)).toBe(2)
    // The three really are different, which is what the section's standing
    // sentence is about.
    expect(new Set([sum(stats.byCondition), sum(stats.byWindBand)]).size).toBe(2)
  })

  it('the temperature sum equals the readable checklists carrying a temperature, which is midpoint banding\'s proof', () => {
    const specs = [50, 52, 58, 30, 90, 70, 86].map(t => ({ comment: srBlock(t) }))
    const { stats } = build(specs)
    const sum = stats.byTempBand.reduce((n, r) => n + r.checklists, 0)
    expect(sum).toBe(7)
    expect(sum).toBe(stats.readableCount)
  })

  it('day + night === the day/night denominator, by construction (FR-22)', () => {
    const { stats } = build([
      { comment: srBlock(60) },
      { comment: srBlock(60, 804, true) },
      { comment: srBlock(60, 804, true) },
      // No header at all, so no day/night field: excluded from the denominator.
      { comment: `Temperature: 60°F  Wind: Calm  Humidity: 50%  ${ATTRIBUTION}` },
    ])
    expect(stats.dayNight).toEqual({ day: 1, night: 2, denominator: 3 })
    expect(stats.dayNight.day + stats.dayNight.night).toBe(stats.dayNight.denominator)
    expect(stats.readableCount).toBe(4)
  })
})

