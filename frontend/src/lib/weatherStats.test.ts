// ── Species and duration (FR-24, FR-25, FR-26) ──────────────────────────────

describe('species and duration averages, and the floor that refuses them (FR-24, FR-25, FR-26)', () => {
  const speciesFor = (i: number) => Array.from({ length: 10 + i }, (_, k) => `Sp ${k}`)

  it('a band with eight checklists averages both figures', () => {
    let i = 0
    const { stats } = build(repeat(8, srBlock(60), () => speciesFor(i++)))
    const row = tempRow(stats, '55 to 64°F')
    expect(row.checklists).toBe(8)
    // speciesCount 10..17 -> mean 13.5
    expect(row.avgSpecies).toBeCloseTo(13.5, 6)
    expect(row.avgDurationMin).toBe(60)
    expect(row.durationCount).toBe(8)
  })

  it('a band with seven checklists shows its count and NO average, and still appears', () => {
    let i = 0
    const { stats } = build(repeat(7, srBlock(60), () => speciesFor(i++)))
    const row = tempRow(stats, '55 to 64°F')
    expect(row.checklists).toBe(7)
    expect(row.avgSpecies).toBeNull()
    expect(row.avgDurationMin).toBeNull()
    // The band is still in the payload — dropping it would make the
    // distribution itself lie.
    expect(stats.byTempBand.length).toBe(7)
  })

  it('the duration figure has its OWN, smaller denominator', () => {
    // Twelve checklists in the band, four of them with a recorded duration.
    let i = 0
    const { stats } = build(repeat(12, srBlock(60), () => speciesFor(i++), n => (n < 4 ? 30 : null)))
    const row = tempRow(stats, '55 to 64°F')
    expect(row.checklists).toBe(12)
    expect(row.durationCount).toBe(4)
    // The band averages SPECIES...
    expect(row.avgSpecies).not.toBeNull()
    // ...and refuses to average four durations inside it. This goes one step
    // past the letter of the band-count rule and squarely with its intent.
    expect(row.avgDurationMin).toBeNull()
  })

  it('the duration average uses only the checklists that have one', () => {
    let i = 0
    const { stats } = build(repeat(10, srBlock(60), () => speciesFor(i++), n => (n < 8 ? 45 : null)))
    const row = tempRow(stats, '55 to 64°F')
    expect(row.checklists).toBe(10)
    expect(row.durationCount).toBe(8)
    expect(row.avgDurationMin).toBe(45)
  })

  it('the same figures are computed on the condition axis', () => {
    let i = 0
    const { stats } = build(repeat(8, srBlock(60, 800), () => speciesFor(i++)))
    const row = condRow(stats, '☀️')
    expect(row.checklists).toBe(8)
    expect(row.avgSpecies).toBeCloseTo(13.5, 6)
    expect(row.avgDurationMin).toBe(60)
  })
})

