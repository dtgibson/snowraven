// ── No ranked or predictive data ────────────────────────────────────────────

describe('the payload offers nothing to rank species by (FR-29)', () => {
  it('carries no ordering by count and no rate', () => {
    const { stats } = build([
      { comment: srBlock(60), species: ['Common Bird', 'Rare Bird'] },
      { comment: srBlock(60), species: ['Common Bird'] },
    ])
    // Sorted by NAME, not by count: "Common Bird" is on two checklists and
    // "Rare Bird" on one, and the order is alphabetical either way.
    expect(stats.species.names).toEqual(['Common Bird', 'Rare Bird'])
    // Nothing in the payload is a rate or a score.
    const keys = new Set<string>()
    const walk = (v: unknown) => {
      if (Array.isArray(v)) { v.forEach(walk); return }
      if (v && typeof v === 'object') {
        for (const k of Object.keys(v)) { keys.add(k); walk((v as Record<string, unknown>)[k]) }
      }
    }
    walk(stats)
    for (const bad of ['rate', 'score', 'rank', 'best', 'likelihood']) {
      expect([...keys].some(k => k.toLowerCase().includes(bad)), bad).toBe(false)
    }
  })
})
