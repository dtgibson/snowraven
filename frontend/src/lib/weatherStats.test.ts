// ── Block builders ──────────────────────────────────────────────────────────

const TZ = 'America/Los_Angeles'
function hourly(over: Partial<HourlyResponse['data'][number]> = {}): HourlyResponse {
  return {
    data: [{
      dt: 1716570000, temp: 64, humidity: 72, dew_point: 55, wind_speed: 6, wind_deg: 250,
      clouds: 20, weather: [{ id: 801, description: 'few clouds' }],
      sunrise: 1716550000, sunset: 1716600000, ...over,
    }],
  }
}

/** A SnowRaven block from the real formatter, at the given temperature. */
function srBlock(temp: number, owmId = 801, night = false): string {
  return formatWeather([hourly({ temp, weather: [{ id: owmId, description: 'x' }], ...(night ? { dt: 1716540000 } : {}) })], TZ, 33.7)
}

/** A RainCrow block, the collapsed single-line shape a real export carries. */
function rcBlock(body: string, header = '⛅'): string {
  return `${header}  Scattered clouds  ${body}  Weather generated by <a href="https://raincrow.app/">RainCrow</a>`
}

/** A block-shaped comment with weather LABELS and NO app attribution — the
 *  comment the attribution gate must refuse. */
function unattributed(body: string): string {
  return `⛅  Scattered clouds  ${body}`
}

// ── Observation builders ────────────────────────────────────────────────────

let seq = 0
const OBS_BASE: Omit<ObservationEntry, 'submissionId' | 'commonName' | 'scientificName'> = {
  date: '2024-05-24', location: 'Pond', locationId: 'L1', latitude: 1, longitude: 2,
  county: 'C', count: 1, breedingCode: null, speciesComments: '', catalogIds: [],
  time: '07:00 AM', duration: 60, distance: 1, area: null, protocol: 'Traveling',
  numObservers: 1, allObsReported: true, checklistComments: '', stateProvince: 'US-CA',
}

interface ChecklistSpec {
  comment: string
  species?: string[]
  duration?: number | null
  /** Extra observation ROWS for a species already listed, to prove counts are
   *  checklists rather than rows. */
  extraRows?: string[]
}

function build(specs: ChecklistSpec[]): { obs: ObservationEntry[]; stats: WeatherStats } {
  const obs: ObservationEntry[] = []
  for (const spec of specs) {
    const sub = `S${100000 + seq++}`
    const names = spec.species ?? ['Anna\'s Hummingbird']
    for (const n of [...names, ...(spec.extraRows ?? [])]) {
      obs.push({
        ...OBS_BASE,
        submissionId: sub,
        commonName: n,
        scientificName: 'Genus species',
        duration: spec.duration === undefined ? 60 : spec.duration,
        checklistComments: spec.comment,
      })
    }
  }
  const checklists = computeChecklists(obs)
  return { obs, stats: computeWeatherStats(checklists, obs) }
}

/** N checklists carrying the same block, each with its own species set. */
function repeat(n: number, comment: string, species: () => string[], duration: (i: number) => number | null = () => 60): ChecklistSpec[] {
  const out: ChecklistSpec[] = []
  for (let i = 0; i < n; i++) out.push({ comment, species: species(), duration: duration(i) })
  return out
}

const condRow = (s: WeatherStats, glyph: string) => s.byCondition[CONDITION_EMOJI.indexOf(glyph as never)]
const tempRow = (s: WeatherStats, label: string) => s.byTempBand[TEMP_BANDS.indexOf(label as never)]

