// Synthetic large eBird "MyEBirdData" export for the big-old-life-lists
// measurement (decisions.md, entry 1). Same 23 columns, header and cell shapes
// as website/tools/gen-demo-data.mjs, scaled to a decades-long world list:
// species drawn from the bundled eBird taxonomy, thousands of hotspots, one
// submission id per checklist, checklist comments that repeat on every row of
// their checklist (about half of them weather blocks, as the app writes them),
// and a small share of historical rows before 1970 and before 1900.
//
// Deterministic (seeded). Fictional data only; no real person's records.
//
//   node gen-big-export.mjs <rows> <out.csv>
import { writeFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const N = Number(process.argv[2] ?? 300000)
const OUT = process.argv[3] ?? join(here, `big-${N}.csv`)

let s = 0x51ed2701
function rnd() { s |= 0; s = (s + 0x6D2B79F5) | 0; let t = Math.imul(s ^ (s >>> 15), 1 | s); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296 }
const pick = (a) => a[Math.floor(rnd() * a.length)]
const rint = (lo, hi) => lo + Math.floor(rnd() * (hi - lo + 1))
const chance = (p) => rnd() < p

const tax = JSON.parse(readFileSync(join(here, '../../../../frontend/src/assets/ebird-taxonomy.json'), 'utf8'))
const world = []
for (const [sciLower, code] of Object.entries(tax.bySci)) {
  const common = tax.byCode[code]
  if (!common || common.includes('/') || common.includes('(')) continue
  const order = tax.byOrder[common.toLowerCase()] ?? 0
  world.push([common, sciLower[0].toUpperCase() + sciLower.slice(1), order])
}

// 60 regions, each with its own species pool and hotspots.
const COUNTRIES = ['US-NY', 'US-NJ', 'US-CA', 'US-TX', 'US-AZ', 'US-FL', 'US-MN', 'US-WA', 'CA-ON', 'CA-BC', 'MX-OAX', 'CR-P', 'EC-P', 'PE-CUS', 'BR-SP', 'AR-B', 'GB-ENG', 'ES-AN', 'KE-110', 'ZA-WC', 'IN-KA', 'TH-50', 'AU-QLD', 'NZ-WGN']
const PLACES = ['Lake', 'Marsh', 'State Park', 'Wildlife Refuge', 'Reservoir', 'Nature Preserve', 'Point', 'Beach', 'Forest', 'Ridge', 'Canyon', 'Wetlands', 'County Park']
const NAMES = ['Willow', 'Heron', 'Cedar', 'Oak Hollow', 'Blue Spring', 'Sandy', 'Pine Barrens', 'Eagle', 'Crane', 'Fox Run', 'Hawk Mountain', 'Mill Creek', 'Riverside', 'Silver', 'Black Rock']
const TRAILS = ['North Loop', 'Boardwalk', 'Visitor Center', 'Overlook', 'South Trail', 'Dike Road', 'Feeders']
const regions = []
for (let r = 0; r < 60; r++) {
  const state = COUNTRIES[r % COUNTRIES.length]
  const pool = []
  const size = rint(250, 700)
  for (let i = 0; i < size; i++) pool.push(pick(world))
  const locs = []
  const nLoc = rint(120, 280)
  const baseLat = -40 + rnd() * 90
  const baseLng = -150 + rnd() * 300
  for (let l = 0; l < nLoc; l++) {
    const name = `${pick(NAMES)} ${pick(PLACES)}${chance(0.6) ? '--' + pick(TRAILS) : ''}`
    locs.push({ name, id: 'L' + rint(100000, 39999999), lat: (baseLat + rnd() * 3).toFixed(4), lng: (baseLng + rnd() * 3).toFixed(4), county: `${pick(NAMES)}`, state })
  }
  regions.push({ pool, locs })
}

const COMMENTS = ['Foraging low in the willows near the water.', 'Singing from the canopy.', 'Pair working a nest cavity.', 'Carrying nest material.', 'Heard only.', 'Flyover heading south.', 'Great looks in good light.', 'High count for this spot.']
const CONDS = ['\u2600\ufe0f  Clear sky', '\u26c5  Scattered clouds', '\u2601\ufe0f  Overcast clouds', '\ud83c\udf27  Light rain']
const CARD = ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW']
function weatherBlock() {
  const t = rint(20, 95)
  return `${pick(CONDS)}  Temperature: ${t}\u00b0F (feels like ${t - rint(0, 6)}\u00b0F)  Wind: ${rint(0, 25)} mph ${pick(CARD)}, gusts ${rint(5, 35)} mph  Humidity: ${rint(20, 99)}%  Pressure: ${rint(990, 1035)} hPa  Visibility: ${rint(1, 10)} mi  Cloud cover: ${rint(0, 100)}%  Sunrise ${rint(5, 7)}:${String(rint(0, 59)).padStart(2, '0')} AM, sunset ${rint(5, 8)}:${String(rint(0, 59)).padStart(2, '0')} PM  Tide: ${(rnd() * 6).toFixed(1)} ft, rising  Moon: waxing gibbous, ${rint(1, 99)}% lit  Weather generated by SnowRaven`
}
function fmtTime(h, m) { const ap = h < 12 ? 'AM' : 'PM'; let hh = h % 12; if (hh === 0) hh = 12; return `${String(hh).padStart(2, '0')}:${String(m).padStart(2, '0')} ${ap}` }
function csvEsc(v) { v = String(v ?? ''); return /[",\n]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v }

const HEADER = ['Submission ID', 'Common Name', 'Scientific Name', 'Taxonomic Order', 'Count', 'State/Province', 'County', 'Location ID', 'Location', 'Latitude', 'Longitude', 'Date', 'Time', 'Protocol', 'Duration (Min)', 'All Obs Reported', 'Distance Traveled (km)', 'Area Covered (ha)', 'Number of Observers', 'Breeding Code', 'Observation Details', 'Checklist Comments', 'ML Catalog Numbers']
const out = [HEADER.join(',')]
let rows = 0
let sub = 100000000
let ml = 100000000
while (rows < N) {
  const reg = pick(regions)
  const loc = pick(reg.locs)
  // Year: mostly 1975-2026, 2% 1900-1969, 0.2% 1850-1899.
  const yr = chance(0.002) ? rint(1850, 1899) : chance(0.02) ? rint(1900, 1969) : rint(1975, 2026)
  const mo = rint(1, 12)
  const dy = rint(1, 28)
  const date = `${yr}-${String(mo).padStart(2, '0')}-${String(dy).padStart(2, '0')}`
  const traveling = chance(0.7)
  const protocol = yr < 1970 ? 'Historical' : traveling ? 'eBird - Traveling Count' : (chance(0.85) ? 'eBird - Stationary Count' : 'eBird - Casual Observation')
  const dur = yr < 1970 ? '' : traveling ? rint(30, 240) : rint(10, 90)
  const dist = traveling && yr >= 1970 ? (Math.round(rnd() * 800) / 100) : ''
  const nobs = chance(0.6) ? 1 : rint(2, 6)
  const allObs = chance(0.85) ? 1 : 0
  const time = yr < 1970 && chance(0.7) ? '' : fmtTime(rint(5, 18), pick([0, 5, 10, 15, 20, 30, 40, 45, 50]))
  const subId = 'S' + (sub++)
  const chk = chance(0.3) ? (chance(0.85) ? `${weatherBlock()}  Notes: ${pick(COMMENTS)} ${pick(COMMENTS)}` : `${pick(COMMENTS)} Trip ${rint(1, 99999)}.`) : ''
  const nSp = Math.min(N - rows, rint(3, 14))
  const seen = new Set()
  for (let k = 0; k < nSp; k++) {
    const sp = pick(reg.pool)
    if (seen.has(sp[0])) continue
    seen.add(sp[0])
    const count = chance(0.06) ? 'X' : String(Math.max(1, Math.round((rnd() ** 2) * 30)))
    const br = mo >= 4 && mo <= 7 && chance(0.1) ? pick(['S Singing Bird', 'P Pair in Suitable Habitat', 'FL Recently Fledged Young', 'ON Occupied Nest', 'CN Carrying Nesting Material']) : ''
    const det = chance(0.09) ? `${pick(COMMENTS)} ${rint(1, 9999)}` : ''
    let mlIds = ''
    if (chance(0.05)) mlIds = chance(0.8) ? `ML${ml++}` : `ML${ml++} ML${ml++}`
    out.push([subId, sp[0], sp[1], sp[2], count, loc.state, loc.county, loc.id, loc.name, loc.lat, loc.lng, date, time, protocol, dur, allObs, dist, '', nobs, br, det, chk, mlIds].map(csvEsc).join(','))
    rows++
  }
}
const text = out.join('\n') + '\n'
writeFileSync(OUT, text)
console.log(JSON.stringify({ rows, chars: text.length, bytes: Buffer.byteLength(text), charsPerRow: +(text.length / rows).toFixed(1), out: OUT }))
